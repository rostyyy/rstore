# Імпортуємо функцію path для створення URL-маршрутів
from django.urls import path

# Імпортуємо модуль views, де знаходиться логіка обробки запитів
from . import views


# Список маршрутів додатку користувачів
urlpatterns = [

    # Реєстрація нового користувача
    # Відображає форму реєстрації та обробляє POST-запит при відправці форми
    # name='register' використовується в шаблонах для побудови URL: {% url 'register' %}
    path('register/', views.register_view, name='register'),

    # Вхід користувача в систему
    # Відображає форму логіну та перевіряє облікові дані користувача
    # Після успішного входу перенаправляє на сторінку, вказану в параметрі next
    path('login/', views.login_view, name='login'),

    # Вихід користувача з системи
    # Викликає функцію logout, яка очищує сесію користувача
    # Після виходу перенаправляє на головну сторінку каталогу
    path('logout/', views.logout_view, name='logout'),

    # Профіль користувача
    # Відображає інформацію про профіль, замовлення та обрані товари
    # Захищено декоратором @login_required - доступно тільки авторизованим
    path('profile/', views.profile_view, name='profile'),

    # Редагування профілю користувача
    # Відображає форму для зміни даних профілю (ім'я, прізвище, email, телефон, адреса)
    # Після збереження перенаправляє на сторінку профілю
    path('profile/edit/', views.profile_edit_view, name='profile_edit'),

    # Деталі конкретного замовлення
    # <int:order_id> - це динамічний параметр, який передає ID замовлення
    # Наприклад: /orders/5/ покаже замовлення з ID=5
    # Відображає повну інформацію про замовлення: товари, статус, адресу доставки
    path('orders/<int:order_id>/', views.order_detail_view, name='order_detail'),

    # Додавання/видалення товару з обраного (wishlist)
    # <int:product_id> - це ID товару, який додається або видаляється з обраного
    # Логіка toggle: якщо товар вже є в обраному - видаляємо, якщо немає - додаємо
    # Параметри color_id та memory_id можуть передаватися через GET-параметри
    path('wishlist/<int:product_id>/', views.wishlist_toggle, name='wishlist_toggle'),
]